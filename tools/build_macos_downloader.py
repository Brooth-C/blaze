"""Freeze the plain PyPI downloader and EJS solver without GPL optional extras.

Install yt-dlp==2026.10.26 and yt-dlp-ejs==0.8.0, without the [default]
extra. The EJS version is pinned by that yt-dlp release's pyproject.toml.
Native arch builds use Python's standard networking implementation, the
separately supplied Node interpreter and the standalone LGPL media tools.
"""

from pathlib import Path
import argparse
import hashlib
import importlib.metadata
import json
import platform
import re
import subprocess
import sys
import tempfile


VERSIONS = {"yt-dlp": "2026.10.26", "yt-dlp-ejs": "0.8.0"}
EXCLUDES = (
    "mutagen", "curl_cffi", "certifi", "requests", "urllib3", "websockets",
    "brotli", "brotlicffi", "Cryptodome", "Crypto", "secretstorage", "jeepney",
    "youtube_dl", "youtube_dlc", "ytdlp_plugins", "pytest", "test",
    "numpy", "onnxruntime", "webview", "PIL", "torch", "scipy", "pandas",
    "matplotlib", "IPython", "rich",
)


def package_notices(distribution, target):
    notices = []
    for member in distribution.files or []:
        if not any(token in member.name.lower() for token in ("license", "licence", "notice", "copying")):
            continue
        source = Path(distribution.locate_file(member))
        if not source.is_file():
            continue
        relative = Path(*[part for part in member.parts if part not in (".", "..")])
        destination = target / relative
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_bytes(source.read_bytes())
        notices.append(destination.relative_to(target).as_posix())
    if not notices:
        raise ValueError("Missing exact package license text: " + distribution.metadata["Name"])
    return notices


def write_spec(path, entrypoint, arch):
    # Override the stock yt-dlp hook, which probes and collects optional GPL
    # and networking dependencies from the build host if they are installed.
    hooks = path.parent / "hooks"
    hooks.mkdir()
    (hooks / "hook-yt_dlp.py").write_text(
        "from PyInstaller.utils.hooks import collect_data_files, copy_metadata\n"
        "datas = collect_data_files('yt_dlp') + collect_data_files('yt_dlp_ejs')\n"
        "datas += copy_metadata('yt-dlp') + copy_metadata('yt-dlp-ejs')\n"
        "hiddenimports = ['yt_dlp.compat._legacy', 'yt_dlp.compat._deprecated',\n"
        "                 'yt_dlp.utils._legacy', 'yt_dlp.utils._deprecated', 'yt_dlp_ejs']\n",
        encoding="utf-8")
    path.write_text(f'''# Generated by tools/build_macos_downloader.py
from PyInstaller.utils.hooks import collect_all
data, binaries, hidden = collect_all('yt_dlp')
ejs_data, ejs_binaries, ejs_hidden = collect_all('yt_dlp_ejs')
a = Analysis([{str(entrypoint)!r}], pathex=[],
             binaries=binaries + ejs_binaries, datas=data + ejs_data,
             hiddenimports=hidden + ejs_hidden,
             hookspath=[{str(hooks)!r}], runtime_hooks=[], excludes={list(EXCLUDES)!r},
             noarchive=False)
pyz = PYZ(a.pure)
exe = EXE(pyz, a.scripts, a.binaries, a.datas, [], name='yt-dlp',
          debug=False, bootloader_ignore_signals=False, strip=False, upx=False,
          console=True, argv_emulation=False, target_arch={arch!r},
          codesign_identity=None, entitlements_file=None)
''', encoding="utf-8")


def build(args):
    if sys.platform != "darwin" or platform.machine() != args.arch:
        raise RuntimeError("Build on a Mac of the selected native architecture.")
    distributions = {}
    for name, expected in VERSIONS.items():
        distribution = importlib.metadata.distribution(name)
        if distribution.version != expected:
            raise ValueError(f"Install {name}=={expected} without optional extras.")
        distributions[name] = distribution
    args.output.mkdir(parents=True, exist_ok=True)
    args.work.mkdir(parents=True, exist_ok=True)
    args.notices.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix="downloader-", dir=args.work) as temporary:
        stage = Path(temporary)
        entrypoint = stage / "yt_dlp_entry.py"
        entrypoint.write_text('''import os
from pathlib import Path
import subprocess
import sys
import tempfile


def launch():
    from yt_dlp import main
    main()


if __name__ == '__main__':
    # Frozen OpenSSL's compiled CA path may point at the build host. Use
    # Apple's public system root store on this Mac without bundling Certifi.
    # Honour an explicitly configured certificate store from the caller.
    if os.environ.get('SSL_CERT_FILE') or '--version' in sys.argv:
        launch()
    else:
        with tempfile.TemporaryDirectory(prefix='blaze-tls-') as folder:
            roots = subprocess.run([
                '/usr/bin/security', 'find-certificate', '-a', '-p',
                '/System/Library/Keychains/SystemRootCertificates.keychain',
            ], check=True, capture_output=True, timeout=15)
            if b'-----BEGIN CERTIFICATE-----' not in roots.stdout:
                raise RuntimeError('The macOS system certificate store could not be read.')
            certificate_file = Path(folder) / 'system-roots.pem'
            certificate_file.write_bytes(roots.stdout)
            os.environ['SSL_CERT_FILE'] = str(certificate_file)
            launch()
''', encoding="utf-8")
        spec = stage / "yt-dlp.spec"
        write_spec(spec, entrypoint, args.arch)
        import PyInstaller.__main__
        PyInstaller.__main__.run(["--noconfirm", "--clean", "--distpath", str(args.output),
                                 "--workpath", str(args.work / "pyinstaller"), str(spec)])
    binary = args.output / "yt-dlp"
    result = subprocess.run([str(binary), "--version"], check=True, text=True, capture_output=True)
    if result.stdout.strip() != VERSIONS["yt-dlp"]:
        raise ValueError("Frozen downloader returned an unexpected version.")
    # Inspect the actual embedded Python modules, including modules brought
    # into the analysis by hooks, before claiming that optional GPL code is absent.
    from PyInstaller.archive.readers import CArchiveReader
    archive = CArchiveReader(str(binary))
    pyz_name = next(name for name in archive.toc if name.endswith(".pyz"))
    modules = archive.open_embedded_archive(pyz_name).toc
    for name in modules:
        if name.split(".", 1)[0] in EXCLUDES:
            raise ValueError("Excluded optional dependency entered the downloader: " + name)
    notice_files = {}
    for name, distribution in distributions.items():
        safe_name = re.sub(r"[^A-Za-z0-9_.-]", "_", name)
        notice_files[name] = package_notices(distribution, args.notices / safe_name)
    manifest = {
        "file": binary.name, "architecture": args.arch, "packages": VERSIONS,
        "python": platform.python_version(), "pyinstaller": importlib.metadata.version("pyinstaller"),
        "sha256": hashlib.sha256(binary.read_bytes()).hexdigest(), "bytes": binary.stat().st_size,
        "excluded_optional_modules": list(EXCLUDES), "licenses": notice_files,
        "sources": {"yt-dlp": "https://github.com/yt-dlp/yt-dlp/tree/" + VERSIONS["yt-dlp"],
                    "yt-dlp-ejs": "https://pypi.org/project/yt-dlp-ejs/0.8.0/"},
    }
    (args.notices / "Blaze-downloader-manifest.json").write_text(
        json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    (args.notices / "Blaze-downloader-build.txt").write_text(
        "Built from plain yt-dlp 2026.10.26 and yt-dlp-ejs 0.8.0 PyPI packages, without [default] extras.\n"
        "yt-dlp is Unlicense. EJS wheels also retain MIT Astring and ISC Meriyah notices.\n"
        "The downloader uses Python standard-library networking and separately supplied Node and FFmpeg.\n"
        "HTTPS uses this Mac's public system root certificates; a caller-supplied SSL_CERT_FILE is honored.\n"
        "Optional Mutagen, curl-cffi and other network backends are excluded and verified absent in its PYZ.\n"
        "Python/OpenSSL and PyInstaller retain their own licenses; their notices accompany the Blaze app.\n"
        "PyInstaller's full copied license includes the bootloader distribution exception.\n"
        "Rebuild: install the exact pinned packages plus the manifest's PyInstaller version on a native Mac;\n"
        "run tools/build_macos_downloader.py with the matching --arch, --output, --work and --notices paths.\n",
        encoding="utf-8")
    print(json.dumps(manifest))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--arch", choices=("arm64", "x86_64"), required=True)
    parser.add_argument("--output", type=Path, required=True, help="Directory for the yt-dlp executable")
    parser.add_argument("--work", type=Path, required=True)
    parser.add_argument("--notices", type=Path, required=True)
    args = parser.parse_args()
    for name in ("output", "work", "notices"):
        setattr(args, name, getattr(args, name).resolve())
    build(args)


if __name__ == "__main__":
    main()
